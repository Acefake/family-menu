/** 按最长别名匹配，避免鳄梨匹配梨、猕猴桃匹配桃；未知名称使用专用兜底线稿。 */
export function foodIcon(name: string): string {
  let match = 'generic'
  let length = 0
  for (const icon of foodIcons) {
    for (const alias of icon.aliases) {
      if (name.includes(alias) && alias.length > length) {
        match = icon.id
        length = alias.length
      }
    }
  }
  return `/pages/feeding/static/${match}.svg`
}
